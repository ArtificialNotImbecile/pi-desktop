export type I18nKey = keyof typeof dictionaries.en;

type I18nContextValue = {
  language: AppLanguage;
  t(key: I18nKey, values?: Record<string, string | number>): string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  t: translate("en")
});

export function I18nProvider(props: { language: AppLanguage; children: ReactNode }) {
  const language: AppLanguage = props.language === "zh" ? "zh" : "en";
  const value = useMemo(() => ({ language, t: translate(language) }), [language]);
  return (
    <I18nContext.Provider value={value}>
      {props.children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function translate(language: AppLanguage) {
  return (key: I18nKey, values: Record<string, string | number> = {}) => {
    const dictionary = dictionaries[language] ?? dictionaries.en;
    let template: string = dictionary[key] ?? dictionaries.en[key] ?? key;
    template = applySimplePlural(template, Number(values.count), language);
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
  };
}

function applySimplePlural(template: string, count: number, language: AppLanguage): string {
  if (language !== "en" || !Number.isFinite(count)) return template;
  return template.replace(/\{count, plural, one \{([^{}]+)\} other \{([^{}]+)\}\}/g, count === 1 ? "$1" : "$2");
}
